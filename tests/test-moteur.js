/* Tests du moteur de correction : équivalences, forme demandée, unités, arrondis, erreurs fréquentes. */
require('../src/moteur.js');
const { M } = globalThis; let ok = 0, ko = 0;
function t(desc, q, ans, unit, want) { const r = M.grade(q, ans, unit); if (r.s === want) ok++; else { ko++; console.log(`ÉCHEC ${desc} : "${ans}" → ${r.s} (${r.t}) au lieu de ${want}`); } }
t('0,5 = 1/2', { v: 0.5 }, '1/2', '', 'ok');
t('1/2 = 0,5', { v: 0.5 }, '0,5', '', 'ok');
t('50/100', { v: 0.5 }, '50/100', '', 'ok');
t('2/4 non irréductible', { v: 0.5, form: 'irr' }, '2/4', '', 'part');
t('−3/4 irréductible', { v: -0.75, form: 'irr' }, '−3/4', '', 'ok');
t('3x+12−2x = x+12', { f: x => x + 12 }, '3x+12−2x', '', 'ok');
t('développer : parenthèses refusées', { f: x => 3 * (x - 4), form: 'dev' }, '3(x−4)', '', 'part');
t('développer : non réduit', { f: x => 3 * x - 12, form: 'dev' }, '2x+x−12', '', 'part');
t('développer ok', { f: x => 3 * x - 12, form: 'dev' }, '3x − 12', '', 'ok');
t('factoriser ok', { f: x => x * x - 9, form: 'fac' }, '(x−3)(x+3)', '', 'ok');
t('factoriser : recopie', { f: x => x * x - 9, form: 'fac' }, 'x²−9', '', 'part');
t('identité fausse', { f: x => (x + 3) ** 2, form: 'dev', errs: [{ f: x => x * x + 9, m: 'double produit' }] }, 'x^2+9', '', 'ko');
t('25 % de 80', { v: 20 }, '80*25/100', '', 'ok');
t('π exact', { v: 9 * Math.PI, form: 'pi' }, '9π', '', 'ok');
t('π approché', { v: 9 * Math.PI, form: 'pi', approx: 'exacte' }, '28,27', '', 'part');
t('unité manquante', { v: 60, unit: '€' }, '60', '', 'part');
t('unité équivalente 2,5 m = 250 cm', { v: 250, unit: 'cm' }, '2,5', 'm', 'ok');
t('unité tapée', { v: 250, unit: 'cm' }, '250 cm', '', 'ok');
t('unité fausse', { v: 12, unit: 'cm²' }, '12', 'cm', 'part');
t('arrondi au dixième', { v: Math.sqrt(96), round: 1 }, '9,8', '', 'ok');
t('arrondi incorrect', { v: Math.sqrt(96), round: 1 }, '9,79', '', 'part');
t('valeur exacte acceptée', { v: Math.sqrt(96), round: 1 }, '√96', '', 'ok');
t('x = 12', { v: 12 }, 'x = 12', '', 'ok');
t('f(x) = 3x', { f: x => 3 * x }, 'f(x) = 3x', '', 'ok');
t('solutions', { type: 'set', set: [2, -5] }, 'x = 2 ou x = −5', '', 'ok');
t('solutions ;', { type: 'set', set: [2, -5] }, '-5 ; 2', '', 'ok');
t('solution manquante', { type: 'set', set: [7, -7] }, 'x = 7', '', 'part');
t('notation scientifique', { v: 34500, form: 'sci' }, '3,45×10^4', '', 'ok');
t('notation non scientifique', { v: 34500, form: 'sci' }, '34,5×10^3', '', 'part');
t('puissance de 10', { v: 1000, form: 'p10' }, '10^3', '', 'ok');
t('facteurs premiers', { v: 360, form: 'primes' }, '2^3 × 3^2 × 5', '', 'ok');
t('facteurs non premiers', { v: 360, form: 'primes' }, '8 × 45', '', 'part');
t('erreur fréquente', { v: 60, errs: [{ v: 20, m: 'réduction' }] }, '20', '', 'ko');
t('écriture illisible', { v: 3 }, '3++', '', 'ko');
t('vide', { v: 3 }, '', '', 'vide');
t('qcm', { type: 'qcm', correct: 2 }, '2', '', 'ok');
console.log(`${ok}/${ok + ko} tests du moteur réussis`); process.exit(ko ? 1 : 0);
